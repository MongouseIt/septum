        }

        return parent::batch($commands, $pks, $contexts); // TODO: Change the autogenerated stub
    }

    // will just resave tasks, cuz we already implemented changing values in table of task
    public function batchMassAction($pks){

        // Sanitize ids.
        $pks = array_unique($pks);
        $pks = ArrayHelper::toInteger($pks);



        // Remove any values of zero.
        if (array_search(0, $pks, true)) {
            unset($pks[array_search(0, $pks, true)]);
        }

        if (empty($pks)) {
            $this->setError(Text::_('JGLOBAL_NO_ITEM_SELECTED'));
            return false;
        }

        // Get table
        $this->table = $this->getTable();

        // Parent exists so we let's proceed
        while (!empty($pks)) {
            // Pop the first ID off the stack
            $pk = array_shift($pks);

            $this->table->reset();

            // Check that the row actually exists
            if (!$this->table->load($pk)) {
                if ($error = $this->table->getError()) {
                    // Fatal error
                    $this->setError($error);

                    return false;
                } else {
                    // Not fatal error
                    $this->setError(Text::sprintf("Can't find item to perform action", $pk));
                    continue;
                }
            }

            // Check the row, will perform also batch mass actions, like priority change ....
            if (!$this->table->check()) {
                $this->setError($this->table->getError());

                return false;
            }

            // Store the row.
            if (!$this->table->store()) {
                $this->setError($this->table->getError());

                return false;
            }

        }

        // Clean the cache
        $this->cleanCache();

        return true;


    }


    /*
     * check if other actions are performed not move/copy
     */
    public function canPerformMassAction()
    {

        $batch = Factory::getApplication()->getInput()->get('batch', [], 'array');

        // if project selected no need to perform it, we perform main batch
        if (!empty($batch['project_id']))
            return false;

        // no mass action found
        if (!isset($batch['mass_action']))
            return false;

        // no mass action used
        if (empty($batch['mass_action']))
            return false;

        foreach ($batch['mass_action'] as $action) {

            // if we found action not empty we perform
            if (!empty($action))
                return true;
        }

        return false;

    }

    /**
     * Batch copy tasks to a new project or current.
     *
     * @param integer $value The new category.
     * @param array $pks An array of row IDs.
     * @param array $contexts An array of item contexts.
     *
     * @return  mixed  An array of new IDs on success, boolean false on failure.
     *
     * @since   11.1
     */
    protected function batchCopy($value, $pks, $contexts)
    {
        $projectId = (int)$value; // this must be checked in future

        $newIds = array();

        // Parent exists so we let's proceed
        while (!empty($pks)) {
            // Pop the first ID off the stack
            $pk = array_shift($pks);

            $this->table->reset();

            // Check that the row actually exists
            if (!$this->table->load($pk)) {
                if ($error = $this->table->getError()) {
                    // Fatal error
                    $this->setError($error);

                    return false;
                } else {
                    // Not fatal error
                    $this->setError(Text::sprintf('JLIB_APPLICATION_ERROR_BATCH_MOVE_ROW_NOT_FOUND', $pk));
                    continue;
                }
            }

            // Alter the title & alias
            $data = $this->generateNewTitle($this->table->title, $projectId, 0, 0, $this->table->alias);

            $this->table->title = $data['0'];
            $this->table->alias = $data['1'];

            // Reset the ID because we are making a copy
            $this->table->id = 0;

            // Unpublish because we are making a copy
            $this->table->state = 0;

            // New Project ID
            $this->table->project_id = $projectId;
            $this->table->milestone_id = 0;
            $this->table->list_id = 0;

            // TODO: Deal with ordering?
            // $table->ordering	= 1;

            // Check the row.
            if (!$this->table->check()) {
                $this->setError($this->table->getError());

                return false;
            }

            // Store the row.
            if (!$this->table->store()) {
                $this->setError($this->table->getError());

                return false;
            }

            // Get the new item ID
            $newId = $this->table->get('id');

            // Add the new ID to the array
            $newIds[$pk] = $newId;
        }

        // Clean the cache
        $this->cleanCache();

        return $newIds;
    }


