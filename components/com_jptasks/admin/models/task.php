    /**
     * Method to watch an item
     *
     * @param array $pks The items to watch
     * @param integer $value 1 to watch, 0 to unwatch
     * @param integer $uid The user id to watch the item
     */
    public function watch(&$pks, $value = 1, $uid = null)
    {
        $user = Factory::getUser($uid);
        $table = $this->getTable();
        $pks = (array)$pks;

        $is_admin = $user->authorise('core.admin', $this->option);
        $my_views = $user->getAuthorisedViewLevels();
        $projects = array();

        $item_type = 'com_jptasks.task';

        // Access checks.
        foreach ($pks as $i => $pk) {
            $table->reset();

            if ($table->load($pk)) {
                if (!$is_admin && !in_array($table->access, $my_views)) {
                    unset($pks[$i]);
                    \Joomla\CMS\Factory::getApplication()->enqueueMessage(Text::_('JERROR_ALERTNOAUTHOR'), 'warning');
                    $this->setError(Text::_('JERROR_ALERTNOAUTHOR'));
                    return false;
                }

                $projects[$pk] = (int)$table->project_id;
            } else {
                unset($pks[$i]);
            }
        }

        // Attempt to watch/unwatch the selected items
        $db = Factory::getDbo();
        $query = $db->getQuery(true);

        foreach ($pks as $i => $pk) {
            $query->clear();

            if ($value == 0) {
                $query->delete('#__jp_ref_observer')
                    ->where('item_type = ' . $db->quote($item_type))
                    ->where('item_id = ' . $db->quote((int)$pk))
                    ->where('user_id = ' . $db->quote((int)$user->get('id')));

                $db->setQuery($query);


                try {
                    $db->execute();
                } catch (RuntimeException $e) {
                    $this->setError($e->getMessage());
                    return false;
                }
            } else {
                $query->select('COUNT(*)')
                    ->from('#__jp_ref_observer')
                    ->where('item_type = ' . $db->quote($item_type))
                    ->where('item_id = ' . $db->quote((int)$pk))
                    ->where('user_id = ' . $db->quote((int)$user->get('id')));

                $db->setQuery($query);
                $count = (int)$db->loadResult();

                if (!$count) {
                    $data = new stdClass;

                    $data->user_id = (int)$user->get('id');
                    $data->item_type = $item_type;
                    $data->item_id = (int)$pk;
                    $data->project_id = (int)$projects[$pk];


                    try {
                        $db->insertObject('#__jp_ref_observer', $data);
                    } catch (RuntimeException $e) {
                        $this->setError($e->getMessage());
                        return false;
                    }
                }
            }
        }

        // Clear the component's cache
        $this->cleanCache();

        return true;
    }


    /**
     * Sends an email to all newly assigned users
     *
     * @param array $uids The users to notify
     * @param integer $task_id The task id
     *
     * @return    void
     */
    protected function notifyAssignedUsers($uids, $pk)
    {
        // Load the relevant task information
        $query = $this->_db->getQuery(true);
        $query->select('a.id, a.project_id, a.milestone_id, a.list_id, a.title, a.description, a.priority')
            ->select('a.start_date, a.end_date')
            ->select('p.title AS p_title, m.title AS ms_title, l.title AS l_title')
            ->from('#__jp_tasks AS a')
            ->join('LEFT', '#__jp_projects AS p ON p.id = a.project_id')
            ->join('LEFT', '#__jp_milestones AS m ON m.id = a.milestone_id')
            ->join('LEFT', '#__jp_task_lists AS l ON l.id = a.list_id')
            ->where('a.id = ' . (int)$pk);

        $this->_db->setQuery($query);
        $task = $this->_db->loadObject();

        if (empty($task)) return;

        // Get the default language
        $def_lang = ComponentHelper::getParams('com_languages')->get('administrator');
        $debug = Factory::getConfig()->get('debug_lang');

        // Email settings
        $mailfrom = Factory::getConfig()->get('mailfrom');
        $fromname = Factory::getConfig()->get('fromname');

        // Own user account
        $user = Factory::getApplication()->getIdentity();

        // mysql nulldate
        $nd = $this->_db->getNullDate();

        // Task link
        $link = Route::_(Uri::root() . JPtasksHelperRoute::getTaskRoute($task->id, $task->project_id, $task->milestone_id, $task->list_id));

        $is_site = Factory::getApplication()->isClient('site');

        // Send to each user...
        foreach ($uids as $uid) {
            // Dont email to self
            if ($uid == $user->id) {
                continue;
            }

            // Get recipient
            $recipient = Factory::getUser($uid);

            // Load the default language of the recipient
            $lang = Language::getInstance($recipient->getParam('site_language', $def_lang), $debug);
            $lang->load('com_joomproject');
            $lang->load('com_jptasks');

            if ($is_site) {
                $lang->load('com_joomproject', JPATH_ADMINISTRATOR);
                $lang->load('com_jptasks', JPATH_ADMINISTRATOR);
            }

            // Prepare subject
            $format = $lang->_('COM_JOOMPROJECT_TASK_EMAIL_ASSIGN_SUBJECT');
            $subject = sprintf($format, $task->p_title, $user->name, $task->title);

            // Prepare text
            $format = $lang->_('COM_JOOMPROJECT_TASK_EMAIL_ASSIGN_MESSAGE');
            $text = array();

            // Title
            $text[] = '* ' . $lang->_('JGLOBAL_TITLE') . ': \n  ' . $task->title . '\n';

            // Milestone
            $text[] = '* ' . $lang->_('COM_JOOMPROJECT_EMAIL_LABEL_MILESTONE_ID') . ': \n  ' . (empty($task->m_title) ? '-' : $task->m_title) . '\n';

            // Task list
            $text[] = '* ' . $lang->_('COM_JOOMPROJECT_EMAIL_LABEL_LIST_ID') . ': \n  ' . (empty($task->l_title) ? '-' : $task->l_title) . '\n';

            // Start
            $text[] = '* ' . $lang->_('COM_JOOMPROJECT_EMAIL_LABEL_START_DATE') . ': \n  '
                . ($task->start_date == $nd ? '-' : HTMLHelper::_('date', $task->start_date, Text::_('DATE_FORMAT_LC3'))) . '\n';

            // End
            $text[] = '* ' . $lang->_('COM_JOOMPROJECT_EMAIL_LABEL_END_DATE') . ': \n  '
                . ($task->end_date == $nd ? '  -' : HTMLHelper::_('date', $task->end_date, Text::_('DATE_FORMAT_LC3'))) . '\n';

            // Priority
            $text[] = '* ' . $lang->_('COM_JOOMPROJECT_EMAIL_LABEL_PRIORITY') . ': \n  ' . JPTasksHelper::priority2string($task->priority) . '\n';

            // Description
            $text[] = '* ' . $lang->_('COM_JOOMPROJECT_EMAIL_LABEL_DESCRIPTION') . ': \n' . strip_tags($task->description);

            // Done. Compile text
            $text = implode('', $text);
            $text = str_replace('\n', "\n", $text);

            $text = sprintf($format, $recipient->name, $user->name, $text, $link)
                . "\n\n" . sprintf($lang->_('COM_JOOMPROJECT_EMAIL_FOOTER'), Uri::root());

            // Mail it
            $result = Factory::getMailer()->sendMail($mailfrom, $fromname, $recipient->email, $subject, $text);

            // Break on the first failure, assuming emails aren't working
            if (!$result) break;
        }
    }


