    /**
     * Method to get a single record.
     *
     * @param integer $pk The id of the primary key.
     * @return    mixed      $item    Object on success, false on failure.
     */
    public function getItem($pk = null)
    {

        $pk = (!empty($pk)) ? $pk : (int)$this->getState($this->getName() . '.id');
        $table = $this->getTable();

        if ($pk > 0) {
            // Attempt to load the row.
            $return = $table->load($pk);

            // Check for a table object error.
            if ($return === false && $table->getError()) {
                $this->setError($table->getError());
                return false;
            }
        }

        // Convert to the JObject before adding other data.
        $properties = $table->getProperties(1);
        $item = \Joomla\Utilities\ArrayHelper::toObject($properties, CMSObject::class);

        // Convert attributes to JRegistry params
        $item->params = new Registry();

        $item->params->loadString((string)$item->attribs);
        $item->attribs = $item->params->toArray();

        // Get the attachments
        $item->attachment = array();


        if (JPApplicationHelper::exists('com_jprepo')) {
            $attachments = $this->getInstance('Attachments', 'JPrepoModel');
            $item->attachment = $attachments->getItems('com_jptasks.task', $item->id);
        }

        // Get the labels
        $model_labels = $this->getInstance('Labels', 'JPModel');
        $item->labels = $model_labels->getConnections('com_jptasks.task', $item->id);

        // Get the Dependencies
        $taskrefs = $this->getInstance('TaskRefs', 'JPtasksModel');
        $item->dependency = $taskrefs->getItems($item->id, true);

        // Get assigned users
        $item->users = $this->getUsers($item->id);

        // Convert seconds to minutes
        if ($item->estimate > 0) {
            $item->estimate = round($item->estimate / 60);
        }

        if (ComponentHelper::isEnabled('com_jpreminders')) {
            $reminders = $this->getInstance('Reminders', 'JPremindersModel');
            $reminders->setState('filter.task_id', $pk);
            $item->reminders = $reminders->getItems();
        }


        return $item;
    }


    /**
     * Method to get assigned users of a task
     *
     * @param integer    The id of the primary key.
     * @return    array      The assigned users
     */
    public function getUsers($pk = NULL)
    {
        if (!$pk) $pk = $this->getState($this->getName() . '.id');
        if (!$pk) return array();

        $db = Factory::getDbo();
        $query = $db->getQuery(true);

        $query->select('user_id')
            ->from('#__jp_ref_users')
            ->where('item_type = ' . $db->quote('com_jptasks.task'))
            ->where('item_id = ' . $db->quote($pk));

        $db->setQuery((string)$query);
        $data = (array)$db->loadColumn();

        return $data;
    }


    /**
     * Returns the milestone id for each given task
     *
     * @param array $pks The tasks
     *
     * @return    array      The milestone ids
     */
    public function getMilestoneIds($pks)
    {
        if (!is_array($pks) || !count($pks)) {
            return array();
        }

        $query = $this->_db->getQuery(true);

        $query->select('id, milestone_id')
            ->from('#__jp_tasks')
            ->where('id IN(' . implode(', ', $pks) . ')');

        try {
            $this->_db->setQuery($query);
            $items = $this->_db->loadAssocList('id', 'milestone_id');
        } catch (RuntimeException $e) {
            $this->setError($e->getMessage());
            return array();
        }

        return $items;
    }


    /**
     * Method to get the record form.
     *
     * @param array      Data for the form.
     * @param boolean    True if the form is to load its own data (default case), false if not.
     * @return    mixed      A JForm object on success, false on failure
     */
    public function getForm($data = array(), $loadData = true)
    {

        // inits
        $params = ComponentHelper::getParams('com_jptasks');
        $jinput = Factory::getApplication()->input;
        $user = Factory::getApplication()->getIdentity();
        $id = (int)$jinput->get('id', 0);
        $task = $jinput->get('task');

        // Get the form.
        $form = $this->loadForm('com_jptasks.task', 'task', array('control' => 'jform', 'load_data' => $loadData));
        if (empty($form)) return false;

	    $enableNotApplicable = ComponentHelper::getParams('com_jptasks')->get('enable_not_applicable', 0);

		// remove not applicable field is not enabled
		if(!$enableNotApplicable){
			$form->removeField('not_applicable');
			$form->setFieldAttribute('complete', 'showon', '');
		}

        // Set default dates for new tasks
        if ($id == 0 && $params->get('use_default_dates', 0)) {

            // Get user timezone
            $user = Factory::getApplication()->getIdentity();
            $userTz = $user->getParam('timezone', Factory::getApplication()->get('offset'));

            // Create date object with user's timezone
            $date = Factory::getDate('now', $userTz);
            $currentDate = $date->format('Y-m-d');

            // Set start date/time
            $startTime = $params->get('default_start_time', '08:00');
            $startDate = Factory::getDate($currentDate . ' ' . $startTime, $userTz);
            // Convert to UTC for storage
            $startDate->setTimezone(new DateTimeZone('UTC'));
            $form->setValue('start_date', null, $startDate->format('Y-m-d H:i:s'));

            // Set end date/time
            $endTime = $params->get('default_end_time', '18:00');
            $endDate = Factory::getDate($currentDate . ' ' . $endTime, $userTz);
            // Convert to UTC for storage
            $endDate->setTimezone(new DateTimeZone('UTC'));
            $form->setValue('end_date', null, $endDate->format('Y-m-d H:i:s'));
        }

        // Check for existing item.
        // Modify the form based on Edit State access controls.
        if ($id != 0 && (!$user->authorise('core.edit.state', 'com_jptasks.task.' . $id)) || ($id == 0 && !$user->authorise('core.edit.state', 'com_jptasks'))) {
            // Disable fields for display.
            $form->setFieldAttribute('state', 'disabled', 'true');
            $form->setFieldAttribute('priority', 'disabled', 'true');
            $form->setFieldAttribute('start_date', 'disabled', 'true');
            $form->setFieldAttribute('end_date', 'disabled', 'true');
            $form->setFieldAttribute('complete', 'disabled', 'true');

            // Disable fields while saving.
            $form->setFieldAttribute('state', 'filter', 'unset');
            $form->setFieldAttribute('priority', 'filter', 'unset');
            $form->setFieldAttribute('start_date', 'filter', 'unset');
            $form->setFieldAttribute('end_date', 'filter', 'unset');
            $form->setFieldAttribute('complete', 'filter', 'unset');
        }

        // Always disable these fields while saving
        $form->setFieldAttribute('alias', 'filter', 'unset');

        // Disable these fields if not an admin
        if (!$user->authorise('core.admin', 'com_jptasks') && !$user->authorise('core.manage', 'com_jptasks')) {
            $form->setFieldAttribute('access', 'disabled', 'true');
            $form->setFieldAttribute('access', 'filter', 'unset');

            $form->setFieldAttribute('rules', 'disabled', 'true');
            $form->setFieldAttribute('rules', 'filter', 'unset');
        }

        // Disable these fields when updating

        if ($id) {
            $form->setFieldAttribute('project_id', 'readonly', 'true');
            $form->setFieldAttribute('project_id', 'required', 'false');

            if ($task != 'save2copy') {
                $form->setFieldAttribute('project_id', 'disabled', 'true');
                $form->setFieldAttribute('project_id', 'filter', 'unset');
            }

            // We still need to inject the project id when reloading the form
            if (!isset($data['project_id'])) {
                $db = Factory::getDbo();
                $query = $db->getQuery(true);

                $query->select('project_id')
                    ->from('#__jp_tasks')
                    ->where('id = ' . $db->quote($id));

                $db->setQuery($query);
                $form->setValue('project_id', null, (int)$db->loadResult());
            }
        }


        return $form;
    }


    /**
     * Method to get the data that should be injected in the form.
     *
     * @return    mixed    The data for the form.
     */
    protected function loadFormData()
    {

        // Check the session for previously entered form data.
        $app = Factory::getApplication();
        $data = $app->getUserState('com_jptasks.edit.' . $this->getName() . '.data', array());

        if (empty($data)) {
            $data = $this->getItem();
            // Set default values
            if ($this->getState($this->getName() . '.id') == 0) {
                $active_id = JPApplicationHelper::getActiveProjectId();

                $milestone = $app->getUserStateFromRequest('com_jptasks.tasks.filter.milestone', 'milestone_id', '');
                $list = $app->getUserStateFromRequest('com_jptasks.tasks.filter.tasklist', 'list_id', '');
                $priority = $app->getUserStateFromRequest('com_jptasks.tasks.filter.priority', 'filter_priority', '');
                $complete = $app->getUserStateFromRequest('com_jptasks.tasks.filter.complete', 'filter_complete', '');
                $state = $app->getUserStateFromRequest('com_jptasks.tasks.filter.published', 'filter_published', '');

                $data->set('project_id', $active_id);

                if (!empty($milestone)) $data->set('milestone_id', (int)$milestone);
                if (!empty($list)) $data->set('list_id', (int)$list);
                if (!empty($priority)) $data->set('priority', (int)$priority);
                if (!empty($complete)) $data->set('complete', (int)$complete);
                if (!empty($state) || $state === '0') $data->set('state', (int)$state);
            }
        }

        return $data;
    }


    /**
     * A protected method to get a set of ordering conditions.
     *
     * @param object    A record object.
     *
     * @return    array     An array of conditions to add to add to ordering queries.
     */
    protected function getReorderConditions($table)
    {
        $condition = array();
        $condition[] = 'project_id = ' . (int)$table->project_id;

        if ($table->list_id) {
            $condition[] = 'list_id = ' . (int)$table->list_id;
        } elseif ($table->milestone_id) {
            $condition[] = 'milestone_id = ' . (int)$table->milestone_id;
        }

        return array(implode(' AND ', $condition));
    }


    /**
     * Prepare and sanitise the table data prior to saving.
     *
     * @param jtable    A JTable object.
     *
     * @return    void
     */
    protected function prepareTable($table)
    {
        $condition = array();

        $condition[] = 'project_id = ' . (int)$table->project_id;

        if ($table->list_id) {
            $condition[] = 'list_id = ' . (int)$table->list_id;
        } elseif ($table->milestone_id) {
            $condition[] = 'milestone_id = ' . (int)$table->milestone_id;
        }

        $condition = implode(' AND ', $condition);

        // Reorder the items within the category so the new item is first
        if (empty($table->id)) {
            $table->reorder($condition . ' AND state >= 0');
        }
    }


    /**
     * Method to save the form data.
     *
     * @param array      The form data
     *
     * @return    boolean    True on success
     */
    public function save($data)
    {


        $input = Factory::getApplication()->getInput()->get('jform', 0, 'array');


        $table = $this->getTable();
        $key = $table->getKeyName();
        $pk = (!empty($data[$key])) ? $data[$key] : (int)$this->getState($this->getName() . '.id');

        $is_new = true;

        // Include the content plugins for the on save events.
        PluginHelper::importPlugin('content');
        $dispatcher = \Joomla\CMS\Factory::getApplication();

        try {
            if ($pk > 0) {
                if ($table->load($pk)) {
                    $is_new = false;
                }
            }

            if (!$is_new) {
                if (isset($input['project_id']) && (int)$input['project_id'] > 0) {
                    $data['project_id'] = (int)$input['project_id'];
                } else {
                    $data['project_id'] = $table->project_id;
                }

            }

            if (!JPApplicationHelper::enabled('com_jpmilestones')) {
                $data['milestone_id'] = ($is_new ? 0 : $table->milestone_id);
            }


            // Handle task completition meta info
            if (isset($data['complete'])) {
                $date = new Date();
                if ($is_new && $data['complete'] == '1') {
                    $data['completed'] = $date->toSql();
                    $data['completed_by'] = Factory::getApplication()->getIdentity()->id;
                }

                if (!$is_new) {
                    if ($data['complete'] == '0') {
                        $data['completed'] = Factory::getDbo()->getNullDate();
                        $data['completed_by'] = '0';
                    } else {
                        if (Factory::getApplication()->getIdentity()->id != $table->completed_by) {
                            $data['completed'] = $date->toSql();
                            $data['completed_by'] = Factory::getApplication()->getIdentity()->id;
                        }
                    }
                }
            }

            // Make sure the title and alias are always unique
            $data['alias'] = '';
            list($title, $alias) = $this->generateNewTitle($data['title'], $data['project_id'], $data['milestone_id'], $data['list_id'], $data['alias'], $pk);

            $data['title'] = $title;
            $data['alias'] = $alias;

            // Handle permissions and access level
            if (isset($data['rules'])) {
                $access = JPAccessHelper::getViewLevelFromRules($data['rules'], intval($data['access']));

                if ($access) {
                    $data['access'] = $access;
                }
            } else {
                if ($is_new) {
                    // Let the table class find the correct access level
                    $data['access'] = 0;
                } else {
                    // Keep the existing access in the table
                    if (isset($data['access'])) {
                        unset($data['access']);
                    }
                }
            }


            // Try to convert estimate string to time
            if (isset($data['estimate'])) {
                if (!is_numeric($data['estimate'])) {
                    $estimate_time = strtotime($data['estimate']);

                    if ($estimate_time === false || $estimate_time <= 0) {
                        $data['estimate'] = 1;
                    } else {
                        $data['estimate'] = $estimate_time - time();
                    }
                } else {
                    // not a literal time, so convert minutes to secs
                    $data['estimate'] = $data['estimate'] * 60;
                }
            }

            // Make item published by default if new
            if (!isset($data['state']) && $is_new) {
                $data['state'] = 1;
            }

            // Make item priority 1 by default if not set
            if (!isset($data['priority']) && $is_new) {
                $data['priority'] = 1;
            }


            // Bind the data.
            if (!$table->bind($data)) {
                $this->setError($table->getError());
                return false;
            }


            // Prepare the row for saving
            $this->prepareTable($table);


            // Check the data.
            if (!$table->check()) {
                $this->setError($table->getError());
                return false;
            }


            // Trigger the onContentBeforeSave event.
            $result = $dispatcher->triggerEvent($this->event_before_save, array($this->option . '.' . $this->name, &$table, $is_new, $data));

            if (in_array(false, $result, true)) {
                $this->setError($table->getError());
                return false;
            }

            JLoader::register('JPmilestonesModelMilestone', JPATH_ADMINISTRATOR . '/components/com_jpmilestones/models/milestone.php');
            $ms_model = $this->getInstance('Milestone', 'JPmilestonesModel', array('ignore_request' => true));

            if ($table->milestone_id > 0 && $table->complete == 1) {
                $ms_progress_before = $ms_model->getProgress(array($table->milestone_id));
            }


            // Store the data.
            if (!$table->store()) {
                $this->setError($table->getError());
                return false;
            }


            // Clean the cache.
            $this->cleanCache();


            // Trigger the onContentAfterSave event.
            $dispatcher->triggerEvent($this->event_after_save, array($this->option . '.' . $this->name, &$table, $is_new, $data));

            $pk_name = $table->getKeyName();

            if (isset($table->$pk_name)) {
                $this->setState($this->getName() . '.id', $table->$pk_name);
            }

            $this->setState($this->getName() . '.new', $is_new);

            $id = $this->getState($this->getName() . '.id');

            // Load the just updated row
            $updated = $this->getTable();
            if ($updated->load($id) === false) return false;

            // Set the active project
            JPApplicationHelper::setActiveProject($updated->project_id);

            // Store entered rate in session
            if (isset($data['rate']) && !empty($data['rate']) && $data['rate'] != '0.00') {
                Factory::getApplication()->setUserState('com_joomproject.jform_rate', $data['rate']);
            }

            // Add to watch list - if not opt-out
            if ($is_new) {
                $plugin = PluginHelper::getPlugin('content', 'jpnotifications');
                $params = new Registry($plugin->params);
                $opt_out = (int)$params->get('sub_method', 0);

                if (!$opt_out) {
                    $cid = array($id);

                    if (!$this->watch($cid, 1)) {
                        return false;
                    }
                }
            }

            // Store the attachments
            if (isset($data['attachment']) && JPApplicationHelper::exists('com_jprepo')) {
                $attachments = $this->getInstance('Attachments', 'JPrepoModel');

                if (!$attachments->getState('item.type')) {
                    $attachments->setState('item.type', 'com_jptasks.task');
                }

                if ($attachments->getState('item.id') == 0) {
                    $attachments->setState('item.id', $this->getState($this->getName() . '.id'));
                }

                if ((int)$attachments->getState('item.project') == 0) {
                    $attachments->setState('item.project', $updated->project_id);
                }

                if (!$attachments->save($data['attachment'])) {
                    $this->setError($attachments->getError());
                    return false;
                }
            }

            // Store the labels
            if (isset($data['labels'])) {
                $labels = $this->getInstance('Labels', 'JPModel');

                if ((int)$labels->getState('item.project') == 0) {
                    $labels->setState('item.project', $updated->project_id);
                }

                $labels->setState('item.type', 'com_jptasks.task');
                $labels->setState('item.id', $id);

                if (!$labels->saveRefs($data['labels'])) {
                    return false;
                }
            }

            // Store the dependencies
            if (isset($data['dependency'])) {
                $taskrefs = $this->getInstance('TaskRefs', 'JPtasksModel');

                if ((int)$taskrefs->getState('item.project') == 0) {
                    $taskrefs->setState('item.project', $updated->project_id);
                }

                $taskrefs->setState('item.id', $id);

                if (!$taskrefs->save($data['dependency'])) {
                    return false;
                }
            }

            // Store users
            if (isset($data['users'])) {
                $this->saveUsers($id, $data['users']);
            }


            // Trigger milestone complete event?
            if ($table->milestone_id > 0 && $table->complete) {
                $ms_progress_after = $ms_model->getProgress(array($table->milestone_id));

                foreach ($ms_progress_before as $mid => $progress) {
                    if ($progress != 100 && $ms_progress_after[$mid] == 100) {
                        $dispatcher->triggerEvent('onJoomprojectComplete', array('com_jpmilestones.milestone', array($mid)));
                    }
                }
            }


        } catch (Exception $e) {
            $this->setError($e->getMessage());
            return false;
        }

        return true;
    }


    /**
     * Method to save the assigned users.
     *
     * @param int        The task id
     * @param array      The users
     *
     * @return    boolean    True on success
     */
    public function saveUsers($pk, $data)
    {
        $item = 'com_jptasks.task';
        $table = Table::getInstance('UserRef', 'JPtable');
        $query = $this->_db->getQuery(true);

        if (!$pk) return true;

        $query->select('a.user_id')
            ->from('#__jp_ref_users AS a')
            ->where('a.item_type = ' . $this->_db->quote($item))
            ->where('a.item_id = ' . $this->_db->quote($pk));

        $this->_db->setQuery((string)$query);
        $list = (array)$this->_db->loadColumn();

        if (!is_array($data)) {
            $data = explode(',', $data);
        } elseif (count($data) == 1) {
            if (strpos($data[0], ',')) {
                $data = explode(',', $data[0]);
            }
        }

        \Joomla\Utilities\ArrayHelper::toInteger($data);

        // Add new references
        $mailto = array();

        foreach ($data as $uid) {
            $table = Table::getInstance('UserRef', 'JPtable');
            $uid = (int)$uid;

            if (!in_array($uid, $list) && $uid != 0) {
                $sdata = array('item_type' => $item,
                    'item_id' => $pk,
                    'user_id' => $uid,
                    'id' => null);

                if (!$table->save($sdata)) {
                    return false;
                }

                $mailto[] = $uid;
                $list[] = $uid;
            }
        }

        // Delete old references
        foreach ($list as $uid) {
            $table = Table::getInstance('UserRef', 'JPtable');
            $uid = (int)$uid;

            if (!in_array($uid, $data) && $uid != 0) {
                if (!$table->load(array('item_type' => $item, 'item_id' => $pk, 'user_id' => $uid))) {
                    return false;
                }

                if (!$table->delete()) return false;
            }
        }


        if (count($mailto)) {

            // Send email notification to assigned users
            if(\Joomla\CMS\Component\ComponentHelper::getParams('com_jptasks')->get('notify_assigned_users',0))
                $this->notifyAssignedUsers($mailto, $pk);

            // Auto-subscribe users for future notifications
            // Get the project id of the task first
            $query->clear();
            $query->select('project_id')
                ->from('#__jp_tasks')
                ->where('id = ' . (int)$pk);

            $this->_db->setQuery($query);
            $pid = (int)$this->_db->loadResult();

            if (!$pid) return true;

            // Get existing subscriptions
            $query->clear();
            $query->select('user_id')
                ->from('#__jp_ref_observer')
                ->where('item_type = ' . $this->_db->quote($item))
                ->where('item_id = ' . (int)$pk)
                ->order('user_id ASC');

            $this->_db->setQuery($query);
            $subs = (array)$this->_db->loadColumn();

            \Joomla\Utilities\ArrayHelper::toInteger($subs);

            // Create dummy object
            $obj = new stdClass();
            $obj->user_id = 0;
            $obj->item_type = $item;
            $obj->item_id = (int)$pk;
            $obj->project_id = $pid;

            // Store each new subscription
