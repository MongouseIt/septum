    /**
     * Method to change the title & alias.
     * Overloaded from JModelAdmin class
     *
     * @param string $title The title
     * @param integer $project The project id
     * @param integer $milestone The milestone id
     * @param integer $list The list id
     * @param string $alias The alias
     * @param integer $id The item id
     *
     *
     * @return    array                    Contains the modified title and alias
     */
    protected function generateNewTitle($title, $project, $milestone = 0, $list = 0, $alias = '', $id = 0)
    {
        $table = $this->getTable();
        $db = Factory::getDbo();
        $query = $db->getQuery(true);

        if (empty($alias)) {
            $alias = Joomla\CMS\Application\ApplicationHelper::stringURLSafe($title);

            if (trim(str_replace('-', '', $alias)) == '') {
                $alias = Joomla\CMS\Application\ApplicationHelper::stringURLSafe(Factory::getDate()->format('Y-m-d-H-i-s'));
            }
        }

        $query->select('COUNT(id)')
            ->from($table->getTableName())
            ->where('alias = ' . $db->quote($alias))
            ->where('project_id = ' . $db->quote((int)$project))
            ->where('milestone_id = ' . $db->quote((int)$milestone))
            ->where('list_id = ' . $db->quote((int)$list));

        if ($id) {
            $query->where('id != ' . intval($id));
        }

        $db->setQuery((string)$query);
        $count = (int)$db->loadResult();

        if ($id > 0 && $count == 0) {
            return array($title, $alias);
        } elseif ($id == 0 && $count == 0) {
            return array($title, $alias);
        } else {
            while ($table->load(array('alias' => $alias, 'project_id' => $project, 'milestone_id' => $milestone, 'list_id' => $list))) {
                $m = null;

                if (preg_match('#-(\d+)$#', $alias, $m)) {
                    $alias = preg_replace('#-(\d+)$#', '-' . ($m[1] + 1) . '', $alias);
                } else {
                    $alias .= '-2';
                }

                if (preg_match('#\((\d+)\)$#', $title, $m)) {
                    $title = preg_replace('#\(\d+\)$#', '(' . ($m[1] + 1) . ')', $title);
                } else {
                    $title .= ' (2)';
                }
            }
        }

        return array($title, $alias);
    }


    /**
     * Batch move tasks to a new Project.
     *
     * @param integer $value The new category ID.
     * @param array $pks An array of row IDs.
     * @param array $contexts An array of item contexts.
     *
     * @return  boolean  True on success.
     *
     * @since   3.8.6
     */
    protected function batchMove($value, $pks, $contexts)
    {
        if (empty($this->batchSet)) {
            // Set some needed variables.
            $this->user = Factory::getApplication()->getIdentity();
            $this->table = $this->getTable();
            $this->tableClassName = get_class($this->table);
            $this->contentType = new \Joomla\CMS\UCM\UCMType;
            $this->type = $this->contentType->getTypeByTable($this->tableClassName);
        }

        $projectId = (int)$value;

        // Parent exists so we proceed
        foreach ($pks as $pk) {
            if (!$this->user->authorise('core.edit', $contexts[$pk])) {
                $this->setError(Text::_('JLIB_APPLICATION_ERROR_BATCH_CANNOT_EDIT'));

                return false;
            }

            // Check that the row actually exists
            if (!$this->table->load($pk)) {
                if ($error = $this->table->getError()) {
                    // Fatal error
                    $this->setError($error);

                    return false;
                } else {
                    // Not fatal error
                    $this->setError(Text::sprintf('JLIB_APPLICATION_ERROR_BATCH_MOVE_ROW_NOT_FOUND', $pk));
                    continue;
                }
            }

            // Set the new category ID
            $this->table->project_id = $projectId;
            $this->table->milestone_id = 0;
            $this->table->list_id = 0;

            // Check the row.
            if (!$this->table->check()) {
                $this->setError($this->table->getError());

                return false;
            }

            // Store the row.
            if (!$this->table->store()) {
                $this->setError($this->table->getError());

                return false;
            }
        }

        // Clean the cache
        $this->cleanCache();

        return true;
    }


    public function batch($commands, $pks, $contexts)
